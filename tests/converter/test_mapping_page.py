def run(*argv):
    """Runs one command line of the tool in this interpreter."""
    out, err = io.StringIO(), io.StringIO()
    with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
        status = mapdoc.main([str(argument) for argument in argv])
    return support.Result(status, out.getvalue(), err.getvalue())


def marker(name):
    return f"{OPENING}{name} -->"


def taken_apart(text):
    """A page as what is outside its generated parts, and what stands in each part by name."""
    outside, parts = [], {}
    name = None
    for line in text.split("\n"):
        if name is None:
            outside.append(line)
            if line.startswith(OPENING):
                name = line[len(OPENING):-len(" -->")]
                parts[name] = []
        elif line == END:
            outside.append(line)
            name = None
        else:
            parts[name].append(line)
    return "\n".join(outside), {name: "\n".join(lines) for name, lines in parts.items()}


def made_up(kind, length, legs):
    """A mapping of made-up legs, each given as `(leg, pin, first_led, strips)`."""
    member, strips = ("width", "rows") if kind == mapping.ROWS else ("height", "columns")
    listed = [{"leg": leg, "pin": pin, "first_led": first_led, strips: list(places)} for leg, pin, first_led, places in legs]
    return mapping.loads(json.dumps({"version": 1, member: length, "legs": listed}).encode("utf-8"))


class Copies(unittest.TestCase):
    """A copy of the page and of the mapping folder, for the tool to work on."""

    def setUp(self):
        folder = tempfile.TemporaryDirectory()
        self.addCleanup(folder.cleanup)
        self.folder = Path(folder.name)
        self.page = self.folder / "mapping.md"
        self.mappings = self.folder / "mapping"
        shutil.copyfile(PAGE, self.page)
        shutil.copytree(MAPPINGS, self.mappings)
        self.tracked = PAGE.read_bytes()

    def tool(self, *options):
        return run(*options, "--page", self.page, "--mapping-dir", self.mappings)

    def change(self, path, old, new):
        """Puts `new` in the place of `old`, which the file holds exactly once."""
        text = path.read_text(encoding="utf-8")
        self.assertEqual(text.count(old), 1, old)
        path.write_text(text.replace(old, new), encoding="utf-8")

    def holds(self):
        """Every file of the copy with its bytes."""
        return {str(path.relative_to(self.folder)): path.read_bytes() for path in sorted(self.folder.rglob("*")) if path.is_file()}

    def refused(self, word, *named):
        """The tool refuses the copy, with and without `--check`, in one line that starts
        with the word and holds every text of `named`, and writes nothing."""
        before = self.holds()
        for options in (("--check",), ()):
            with self.subTest(options=options):
                result = self.tool(*options)
                self.assertEqual((result.status, result.out), (1, ""))
                self.assertTrue(result.err.startswith(f"error: {word}: "), result.err)
                self.assertEqual(result.err.count("\n"), 1, result.err)
                for text in named:
                    self.assertIn(text, result.err)
                self.assertEqual(self.holds(), before)


