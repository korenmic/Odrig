class StandardLibraryOnly(unittest.TestCase):
    def test_it_runs_where_no_third_party_library_is_installed(self):
        # -S leaves out the folder that installed libraries live in.
        done = subprocess.run([sys.executable, "-S", "-m", "odrig.mapdoc", "--check"], cwd=support.ROOT, capture_output=True, text=True)
        self.assertEqual((done.returncode, done.stdout, done.stderr), (0, "", ""))

    def test_it_loads_nothing_but_the_standard_library_and_this_package(self):
        script = (
            "import json, sys\n"
            "from odrig import mapdoc\n"
            "status = mapdoc.main(['--check'])\n"
            "loaded = {name.split('.')[0] for name in sys.modules}\n"
            "print(json.dumps({'status': status, 'other': sorted(loaded - set(sys.stdlib_module_names) - {'odrig', '__main__'})}))\n"
        )
        done = subprocess.run([sys.executable, "-S", "-c", script], cwd=support.ROOT, capture_output=True, text=True)
        self.assertEqual((done.returncode, done.stderr), (0, ""))
        self.assertEqual(json.loads(done.stdout), {"status": 0, "other": []})


